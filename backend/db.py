from contextlib import contextmanager
from datetime import datetime, timezone
import os
from pathlib import Path
import sqlite3
from typing import Iterator

import psycopg
from psycopg.rows import dict_row

from .attachment_policy import MAX_ATTACHMENT_BYTES

DB_PATH = Path(os.environ.get("TODO_DB_PATH", Path(__file__).with_name("todos.db")))


def utc_timestamp() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, query, parameters=()):
        return self.connection.execute(query.replace("?", "%s"), parameters)


@contextmanager
def database(*, write=False) -> Iterator[sqlite3.Connection | PostgresConnection]:
    url = os.environ.get("DATABASE_URL")
    if url:
        with psycopg.connect(url, connect_timeout=5, prepare_threshold=None, row_factory=dict_row) as connection:
            yield PostgresConnection(connection)
        return
    connection = sqlite3.connect(DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    try:
        if write:
            connection.execute("BEGIN IMMEDIATE")
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def assign_legacy_tasks(connection: sqlite3.Connection) -> None:
    email = os.environ.get("TODO_LEGACY_OWNER_EMAIL", "").strip().lower()
    if email:
        connection.execute(
            """UPDATE tasks SET user_id = (
                SELECT id FROM users WHERE email = ? AND email_verified = 1
            ) WHERE user_id IS NULL""",
            (email,),
        )


def table_columns(connection: sqlite3.Connection | PostgresConnection, table: str) -> set[str]:
    if isinstance(connection, PostgresConnection):
        rows = connection.execute("""
            SELECT attname FROM pg_attribute
            WHERE attrelid = to_regclass(?) AND attnum > 0 AND NOT attisdropped
        """, (table,)).fetchall()
        return {row["attname"] for row in rows}
    return {row["name"] for row in connection.execute(f"PRAGMA table_info({table})")}


def init_access_controls(connection: sqlite3.Connection | PostgresConnection) -> None:
    connection.execute("CREATE INDEX IF NOT EXISTS sessions_by_expiration ON sessions (expires_at)")
    connection.execute("""
        CREATE TABLE IF NOT EXISTS request_limits (
            action TEXT NOT NULL,
            bucket TEXT NOT NULL,
            resets_at BIGINT NOT NULL,
            attempts INTEGER NOT NULL,
            PRIMARY KEY (action, bucket, resets_at)
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS request_limits_by_expiration ON request_limits (resets_at)")


def init_workspaces(connection: sqlite3.Connection | PostgresConnection) -> None:
    postgres = isinstance(connection, PostgresConnection)
    primary_key = "BIGINT GENERATED BY DEFAULT AS IDENTITY" if postgres else "INTEGER"
    reference = "BIGINT" if postgres else "INTEGER"
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS workspaces (
            id {primary_key} PRIMARY KEY,
            name TEXT NOT NULL,
            owner_id {reference} NOT NULL REFERENCES users(id)
        )
    """)
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS workspace_members (
            workspace_id {reference} NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
            user_id {reference} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            can_change_status INTEGER NOT NULL DEFAULT 0 CHECK (can_change_status IN (0, 1)),
            PRIMARY KEY (workspace_id, user_id)
        )
    """)
    if "can_change_status" not in table_columns(connection, "workspace_members"):
        connection.execute("""
            ALTER TABLE workspace_members ADD COLUMN can_change_status
            INTEGER NOT NULL DEFAULT 0 CHECK (can_change_status IN (0, 1))
        """)
    connection.execute("CREATE INDEX IF NOT EXISTS workspace_members_by_user ON workspace_members (user_id)")
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS workspace_invitations (
            workspace_id {reference} NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
            email TEXT NOT NULL,
            token_hash TEXT NOT NULL UNIQUE,
            expires_at {reference} NOT NULL,
            recipient_id {reference} REFERENCES users(id) ON DELETE CASCADE,
            PRIMARY KEY (workspace_id, email)
        )
    """)
    if "recipient_id" not in table_columns(connection, "workspace_invitations"):
        connection.execute(f"""
            ALTER TABLE workspace_invitations ADD COLUMN recipient_id {reference}
            REFERENCES users(id) ON DELETE CASCADE
        """)
    connection.execute("""
        CREATE INDEX IF NOT EXISTS invitations_by_recipient
        ON workspace_invitations (recipient_id, expires_at)
    """)
    task_columns = {
        "workspace_id": f"{reference} REFERENCES workspaces(id) ON DELETE CASCADE",
        "board_status": "TEXT NOT NULL DEFAULT 'todo' CHECK (board_status IN ('todo', 'doing', 'done'))",
        "board_position": "BIGINT NOT NULL DEFAULT 0",
    }
    columns = table_columns(connection, "tasks")
    for column, definition in task_columns.items():
        if column not in columns:
            connection.execute(f"ALTER TABLE tasks ADD COLUMN {column} {definition}")

    connection.execute("CREATE INDEX IF NOT EXISTS tasks_by_workspace ON tasks (workspace_id)")
    connection.execute("""
        CREATE INDEX IF NOT EXISTS tasks_by_board_position
        ON tasks (workspace_id, board_status, board_position, id DESC)
    """)
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS task_comments (
            id {primary_key} PRIMARY KEY,
            task_id {reference} NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
            author_id {reference} NOT NULL REFERENCES users(id),
            body TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS comments_by_task ON task_comments (task_id, id)")
    autoincrement = "" if postgres else " AUTOINCREMENT"
    binary_type = "BYTEA" if postgres else "BLOB"
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS task_attachments (
            id {primary_key} PRIMARY KEY{autoincrement},
            task_id {reference} NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
            uploaded_by {reference} NOT NULL REFERENCES users(id),
            file_name TEXT NOT NULL,
            size_bytes INTEGER NOT NULL CHECK (size_bytes BETWEEN 0 AND {MAX_ATTACHMENT_BYTES}),
            content {binary_type} NOT NULL,
            created_at TEXT NOT NULL
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS attachments_by_task ON task_attachments (task_id, id)")
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS friendships (
            id {primary_key} PRIMARY KEY{autoincrement},
            user_low {reference} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            user_high {reference} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            requested_by {reference} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
            UNIQUE (user_low, user_high),
            CHECK (user_low < user_high AND requested_by IN (user_low, user_high))
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS friendships_by_high_user ON friendships (user_high)")
    connection.execute(f"""
        CREATE TABLE IF NOT EXISTS direct_messages (
            id {primary_key} PRIMARY KEY{autoincrement},
            friendship_id {reference} NOT NULL REFERENCES friendships(id) ON DELETE CASCADE,
            author_id {reference} NOT NULL REFERENCES users(id),
            body TEXT NOT NULL,
            created_at TEXT NOT NULL
        )
    """)
    connection.execute("CREATE INDEX IF NOT EXISTS direct_messages_by_chat ON direct_messages (friendship_id, id)")


def init_db() -> None:
    if os.environ.get("DATABASE_URL"):
        init_postgres()
        return

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with database(write=True) as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                email_verified INTEGER NOT NULL DEFAULT 0
            )
        """)
        user_columns = {row["name"] for row in connection.execute("PRAGMA table_info(users)")}
        if "email_verified" not in user_columns:
            connection.execute("ALTER TABLE users ADD COLUMN email_verified INTEGER NOT NULL DEFAULT 0")
            connection.execute("UPDATE users SET email_verified = 1 WHERE password_hash IS NOT NULL")
            if {"activation_hash", "activation_sent_at"} <= user_columns:
                connection.execute("UPDATE users SET activation_hash = NULL, activation_sent_at = NULL")
        connection.execute("""
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at INTEGER NOT NULL
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS tasks (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL REFERENCES users(id),
                title TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                start_date TEXT NOT NULL,
                end_date TEXT NOT NULL,
                completed INTEGER NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now')),
                updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
            )
        """)
        columns = {row["name"] for row in connection.execute("PRAGMA table_info(tasks)")}
        for column in ("start_date", "end_date"):
            if column not in columns:
                connection.execute(f"ALTER TABLE tasks ADD COLUMN {column} TEXT")
        if "user_id" not in columns:
            connection.execute("ALTER TABLE tasks ADD COLUMN user_id INTEGER REFERENCES users(id)")
        connection.execute(
            "UPDATE tasks SET start_date = COALESCE(start_date, substr(created_at, 1, 10)), "
            "end_date = COALESCE(end_date, start_date, substr(created_at, 1, 10)) "
            "WHERE start_date IS NULL OR end_date IS NULL"
        )
        connection.execute("CREATE INDEX IF NOT EXISTS tasks_by_user ON tasks (user_id)")
        assign_legacy_tasks(connection)
        init_access_controls(connection)
        init_workspaces(connection)


def init_postgres() -> None:
    with database(write=True) as connection:
        connection.execute("SELECT pg_advisory_xact_lock(638102597)")
        connection.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS sessions (
                token_hash TEXT PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                expires_at BIGINT NOT NULL
            )
        """)
        connection.execute("""
            CREATE TABLE IF NOT EXISTS tasks (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT NOT NULL REFERENCES users(id),
                title TEXT NOT NULL,
                description TEXT NOT NULL DEFAULT '',
                start_date TEXT NOT NULL,
                end_date TEXT NOT NULL,
                completed BOOLEAN NOT NULL DEFAULT FALSE,
                created_at TEXT NOT NULL DEFAULT to_char(
                    CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'
                ),
                updated_at TEXT NOT NULL DEFAULT to_char(
                    CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'
                )
            )
        """)
        connection.execute("CREATE INDEX IF NOT EXISTS tasks_by_user ON tasks (user_id)")
        init_access_controls(connection)
        init_workspaces(connection)
